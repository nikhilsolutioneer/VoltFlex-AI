import { useId, useRef, useState } from 'react'
import type { FoundryConfig } from './useFoundryConfig'

export function FoundrySettings({ config, busy }: { config: FoundryConfig; busy: boolean }) {
  const [open, setOpen] = useState(false)
  const settingsId = useId()
  const toggle = useRef<HTMLButtonElement>(null)

  function close() {
    setOpen(false)
    toggle.current?.focus()
  }

  return (
    <div className="foundry-settings-host">
      <div className="foundry-heading">
        <p className="muted">{config.configured
          ? `Answers are generated by ${config.deployment}. ${config.dataAgentReady ? 'Grounded in live Fabric data agent readings.' : 'No data agent token yet.'}`
          : 'Open the settings gear to add your endpoint, model deployment, API key and Fabric data agent token.'}</p>
        <button ref={toggle} className="settings-toggle" type="button"
          aria-label="Foundry settings" title="Foundry settings"
          aria-expanded={open} aria-controls={settingsId}
          onClick={() => setOpen((current) => !current)}>
          <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor"
            strokeWidth="1.6" strokeLinejoin="round" aria-hidden="true" focusable="false">
            <path d="M10 2h4l.6 3 2.1 1.2 2.9-.9 2 3.4-2.3 2.1v2.4l2.3 2.1-2 3.4-2.9-.9-2.1 1.2-.6 3h-4l-.6-3-2.1-1.2-2.9.9-2-3.4 2.3-2.1v-2.4L2.4 8.7l2-3.4 2.9.9L9.4 5Z" />
            <circle cx="12" cy="12" r="3" />
          </svg>
        </button>
      </div>
      {open && (
        <form id={settingsId} className="foundry-settings" aria-label="Foundry settings"
          onSubmit={(event) => { event.preventDefault(); close() }}
          onKeyDown={(event) => {
            if (event.key === 'Escape') {
              event.preventDefault()
              event.stopPropagation()
              close()
            }
          }}>
          <p className="warning"><strong>Demo only.</strong> The key stays in page memory but is visible to this browser,
            extensions, developer tools and any injected script. Use a disposable demo resource, not a shared production key.</p>
          <label htmlFor="foundry-endpoint">Foundry resource endpoint</label>
          <input id="foundry-endpoint" type="url" value={config.endpoint} required disabled={busy}
            placeholder="https://your-resource.openai.azure.com/"
            onChange={(event) => config.setEndpoint(event.target.value)} />
          <div className="foundry-settings-fields">
            <div>
              <label htmlFor="foundry-deployment">Model deployment name</label>
              <input id="foundry-deployment" value={config.deployment} required disabled={busy}
                onChange={(event) => config.setDeployment(event.target.value)} />
            </div>
            <div>
              <label htmlFor="foundry-key">Your Foundry API key (memory only)</label>
              <input id="foundry-key" type="password" value={config.apiKey} required disabled={busy}
                autoComplete="off" spellCheck={false} onChange={(event) => config.setApiKey(event.target.value)} />
            </div>
          </div>
          <p className="muted">Clear key, sign-out, account change or reload removes this page&rsquo;s reference.
            Closing settings keeps it in memory for this session. This cannot recall an already-sent request.</p>

          <label htmlFor="data-agent-token">Fabric data agent token (memory only)</label>
          <textarea id="data-agent-token" value={config.dataAgentToken} rows={3} disabled={busy}
            autoComplete="off" spellCheck={false} placeholder="Paste the access token from az account get-access-token"
            onChange={(event) => config.setDataAgentToken(event.target.value)} />
          <p className="muted">Generate with <code>az account get-access-token --resource https://api.fabric.microsoft.com --query accessToken -o tsv</code>.
            These tokens expire after about an hour, and an expired one is reported as an invalid request.</p>

          <button className="secondary" type="submit" disabled={busy}>Done</button>
        </form>
      )}
    </div>
  )
}
